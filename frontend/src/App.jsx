import { useState, useRef } from 'react';
import ReactMarkdown from 'react-markdown';
import html2pdf from 'html2pdf.js';
import Upload from './components/Upload';
import './index.css';

const DownloadIcon = () => (
  <svg width="20" height="20" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg" style={{ marginRight: '8px' }}>
    <path d="M12 2V13M12 13L8 9M12 13L16 9" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round"/>
    <path d="M3 15C3 17.5 5 19.5 7.5 19.5H16.5C19 19.5 21 17.5 21 15" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round"/>
    <circle cx="17.5" cy="16.5" r="1.2" fill="currentColor"/>
  </svg>
);

function App() {
  const [results, setResults] = useState(null);
  const pdfRef = useRef(null);

  const handleResults = (data) => {
    setResults(data);
  };

  const clearResults = () => {
    setResults(null);
  };

  const downloadPDF = () => {
    const element = pdfRef.current;
    const opt = {
      margin:       [15, 15],
      filename:     'Lecture_Notes.pdf',
      image:        { type: 'jpeg', quality: 0.98 },
      html2canvas:  { scale: 2, useCORS: true, letterRendering: true },
      jsPDF:        { unit: 'mm', format: 'a4', orientation: 'portrait' },
      pagebreak:    { mode: ['avoid-all', 'css', 'legacy'] }
    };

    html2pdf().set(opt).from(element).save();
  };

  return (
    <div className="app-container">
      <header className="header">
        <h1>AI Lecture Notes</h1>
        <p>Transform your audio lectures into structured, comprehensive notes in seconds.</p>
      </header>

      <main className="main-content">
        {!results ? (
          <Upload onResults={handleResults} />
        ) : (
          <div className="results-container">
            <div className="results-actions">
              <button className="back-btn" onClick={clearResults}>
                &#8592; Process Another Audio
              </button>
              <button className="download-btn" onClick={downloadPDF}>
                 <DownloadIcon /> Download PDF Notes
              </button>
            </div>

            <div className="results-grid">
               <div className="result-card glass-card transcript-section">
                  <h3>Original Transcript</h3>
                  <div className="scrollable-content">
                     <p>{results.transcript}</p>
                  </div>
               </div>

               <div className="result-card glass-card notes-section">
                  <h3>Generated Notes</h3>
                  <div className="scrollable-content markdown-body">
                      <ReactMarkdown>{results.notes}</ReactMarkdown>
                  </div>
               </div>
            </div>

            {/* Hidden PDF Template for High Quality Export */}
            <div style={{ display: 'none' }}>
              <div ref={pdfRef} className="pdf-export-content">
                <div className="pdf-header">
                  <h1>Lecture Notes</h1>
                  <p className="pdf-date">Generated on {new Date().toLocaleDateString()} at {new Date().toLocaleTimeString()}</p>
                </div>
                <div className="pdf-body markdown-body">
                  <ReactMarkdown>{results.notes}</ReactMarkdown>
                </div>
                <div className="pdf-footer">
                  <p>Generated by AI Lecture Notes Generator</p>
                </div>
              </div>
            </div>
          </div>
        )}
      </main>
    </div>
  );
}

export default App;
